  VALUES ('NEG_PUBLICADO_SEM_SOMBRA_APROVADA', 'NEGATIVA', 'RECUSADO',
          CASE WHEN aceito THEN 'ACEITO' ELSE 'RECUSADO: ' || estado END,
          CASE WHEN aceito THEN 'FAIL' ELSE 'PASS' END);
END $neg$;  -- publicar sem a validacao sombra ter passado

