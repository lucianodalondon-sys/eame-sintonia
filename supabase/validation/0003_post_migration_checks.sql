DECLARE aceito boolean := false; estado text := '';
BEGIN
  BEGIN
    insert into publish_run (publish_run_id, pipeline_version, schema_version, status, shadow_validation_passed) values ('RUN-X', 'x', 'x', 'PUBLISHED', false);
    aceito := true;
    RAISE EXCEPTION 'DESFAZER_A_LINHA_QUE_NAO_DEVIA_TER_ENTRADO';
  EXCEPTION WHEN others THEN
    estado := SQLSTATE;
  END;
